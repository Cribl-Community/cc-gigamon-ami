// ── Reading ─────────────────────────────────────────────────────────────────

/** This pack as the group's pack list reports it. */
export interface Installed {
  version: string | null
  /** Where Cribl says the copy was installed from (PackInfo `source`). */
  source: string | null
}

/** The group's copy of this pack, `null` when it is not installed, or an error
 *  sentence when the list could not be read — which is never "not installed".
 *  Exported for packUpgrade.ts, which holds the in-place upgrade. */
export async function readInstalled(group: string): Promise<{ pack: Installed | null } | { error: string }> {
  const r = await capi('GET', groupPath(group, '/packs'))
  if (r.status !== 200) return { error: `the group’s pack list could not be read (HTTP ${r.status})` }
  const list = (r.body as { items?: unknown })?.items
  if (!Array.isArray(list)) return { error: 'the group’s pack list came back in a shape this app cannot read' }
  const mine = list.find((p) => p && typeof p === 'object' && (p as { id?: unknown }).id === PACK_ID) as
    | { version?: unknown; source?: unknown }
    | undefined
  if (!mine) return { pack: null }
  const text = (v: unknown) => (typeof v === 'string' && v ? v : null)
  return { pack: { version: text(mine.version), source: text(mine.source) } }
}

/** The two ownership signals, each on its own (see the header). */
function ownership(p: Installed): { published: boolean; fromRelease: boolean } {
  const v = p.version
  return {
    published: v !== null && PUBLISHED_PACK_VERSIONS.includes(v),
    fromRelease: v !== null && p.source === packReleaseUrl(v),
  }
}

/** Why the installed copy is not this app's to upgrade or remove, or null. The
 *  install source is never repeated: a Git URL can carry credentials. Exported
 *  for packUpgrade.ts. */
export function notOurs(p: Installed): string | null {
  const { published, fromRelease } = ownership(p)
  if (!published) return `kept — the installed ${PACK_ID} is version ${p.version ?? 'unknown'}, which this app did not publish`
  if (!fromRelease) {
    return `kept — the installed ${PACK_ID} ${p.version} was not installed from this app’s release of that version ` +
      `(the group’s pack list names ${p.source ? 'another source' : 'no source'}), so this app does not treat it as its own`
  }
  return null
}

/** `a` compared with `b` as dotted numbers: negative, zero or positive. A part
 *  that is not a number compares as 0, which only matters for a version this
 *  app did not publish — and those are refused before any comparison. */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map((x) => Number.parseInt(x, 10) || 0)
  const pb = b.split('.').map((x) => Number.parseInt(x, 10) || 0)
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0)
    if (d !== 0) return d
  }
  return 0
}

