/**
 * The `tls` block to set on the Raw HTTP source, or null to leave the live one.
 *
 * A TLS BLOCK THE SOURCE ALREADY HAS IS SOMEBODY'S DECISION, and is kept: a
 * certificate added to a hybrid group after the install, or a managed group's
 * own certificate. Overwriting it with `tlsFor(hosting)` put a hybrid group
 * back on plaintext on the next enable. Two cases are set:
 *   * no TLS block at all — TLS for the group's hosting;
 *   * a hybrid group still on the pack's shipped block, which names
 *     `$CRIBL_CLOUD_CRT`, a certificate that does not exist there (the source
 *     would never start) — TLS off, which the endpoint card says plainly.
 */
function tlsToSet(live: Record<string, unknown>, hosting: 'managed' | 'hybrid'): Record<string, unknown> | null {
  const tls = live.tls
  if (!tls || typeof tls !== 'object' || Array.isArray(tls)) return tlsFor(hosting === 'managed')
  if (hosting === 'hybrid' && sameValue(tls, SHIPPED_TLS)) return tlsFor(false)
  return null
}

/** The ports every other source in the group listens on — its own, and other
 *  packs' — or null when any could not be read ("cannot tell" is never "free"). */
export async function portsOfOthers(group: string): Promise<number[] | null> {
  const inputs = await groupInputs(group)
  if (!inputs) return null
  return portsInUse(inputs.filter((i) => !(i.pack === PACK_ID && i.id === PACK_HTTP_INPUT_ID)))
}

/** Why an enabled source here would be unsafe, or null. */
function enableProblem(live: Record<string, unknown>, hosting: 'managed' | 'hybrid', used: number[] | null): string | null {
  if (tokensOf(live).length === 0) {
    return 'not enabled — the source has no auth token, so it would accept a POST from anyone who can reach the port'
  }
  const port = numberOr(live.port)
  if (port === null) return 'not enabled — this app cannot read the source’s port'
  const problem = portProblem(port, hosting === 'managed', used)
  return problem ? `not enabled — port ${port}: ${problem}` : null
}

/** The change as a plan against the live source, or the refusal that needs no
 *  read of it. Reads the group's ports, or Lake's datasets, where the change
 *  depends on them — GETs only. */
async function planFor(group: string, change: PackInputChange): Promise<Plan | PackStep> {
  const refuse = (detail: string): PackStep => ({ key: change.kind === 'sample' ? 'sample_input' : 'http_input', action: 'error', detail })
  switch (change.kind) {
    case 'configure': {
      const { port, token, hosting } = change
      if (!hosting) return refuse(NO_HOSTING)
      if (!TOKEN_SHAPE.test(token)) return refuse(BAD_TOKEN)
      const problem = portProblem(port, hosting === 'managed', await portsOfOthers(group))
      if (problem) return refuse(`not applied — port ${port}: ${problem}`)
      return {
        which: 'http',
        edit: (live) => {
          const tls = tlsToSet(live, hosting)
          return { set: { port, ...(tls ? { tls } : {}), authTokensExt: [{ token, authType: 'manual' }], disabled: false } }
        },
        secrets: [token],
      }
    }
    case 'port': {
      const { port, hosting } = change
      if (!hosting) return refuse(NO_HOSTING)
      const problem = portProblem(port, hosting === 'managed', await portsOfOthers(group))
      if (problem) return refuse(`not applied — port ${port}: ${problem}`)
      return { which: 'http', edit: () => ({ set: { port } }), secrets: [] }
    }
    case 'token': {
      const { token } = change
      if (!TOKEN_SHAPE.test(token)) return refuse(BAD_TOKEN)
      return { which: 'http', edit: () => ({ set: { authTokensExt: [{ token, authType: 'manual' }] } }), secrets: [token] }
    }
    case 'enable': {
      const { hosting } = change
      if (!hosting) return refuse(NO_HOSTING)
      const used = await portsOfOthers(group)
      return {
        which: 'http',
        edit: (live) => {
          const problem = enableProblem(live, hosting, used)
          if (problem) return { refuse: problem }
          const tls = tlsToSet(live, hosting)
          return { set: { disabled: false, ...(tls ? { tls } : {}) } }
        },
        secrets: [],
      }
    }
    case 'sample': {
      if (change.enabled) {
        const datasets = await listDatasets()
        if (datasets.outcome !== 'ok') {
          return refuse(`not started — Cribl Lake’s dataset list could not be read, so this app cannot check ${PACK_SAMPLE_DATASET_ID} exists`)
        }
        if (!(datasets.value ?? []).some((d) => d.id === PACK_SAMPLE_DATASET_ID)) {
          return refuse(`not started — the ${PACK_SAMPLE_DATASET_ID} dataset does not exist yet`)
        }
      }
      return { which: 'sample', edit: () => ({ set: { disabled: !change.enabled } }), secrets: [] }
    }
  }
}

/** Read one of the pack's sources whole. Two literal paths, not one built from
 *  `which`, so policyCoverage.test.ts can read each call site. */
async function readLive(group: string, which: Which) {
  return which === 'http'
    ? capi('GET', packPath(group, `/system/inputs/${PACK_HTTP_INPUT_ID}`))
    : capi('GET', packPath(group, `/system/inputs/${PACK_SAMPLE_INPUT_ID}`))
}

/**
 * The before→after of setting `set` on `live`, key by key and sorted, for
 * `<ConfirmDialog diff>`. A key the change leaves as it is gives no row. Token
 * values never appear: `authTokensExt` reads "a token is set (not shown)" →
 * "a new token (not shown)".
 */
function diffOf(live: Record<string, unknown>, set: Record<string, unknown>): DiffRow[] {
  const rows: DiffRow[] = []
  for (const key of Object.keys(set).sort()) {
    const after = set[key]
    const had = Object.hasOwn(live, key) && live[key] !== undefined
    if (had && sameValue(live[key], after)) continue
    if (key === 'authTokensExt') {
      rows.push({
        key, kind: had ? 'changed' : 'added',
        before: had ? (tokensOf({ authTokensExt: live[key] }).length ? 'a token is set (not shown)' : 'no token') : undefined,
        after: 'a new token (not shown)',
      })
      continue
    }
    rows.push({ key, kind: had ? 'changed' : 'added', before: had ? live[key] : undefined, after })
  }
  return rows
}

/** Read the live source and decide the change against it: what to set, its
 *  diff and what to scrub — or the step that ends it without a write. */
async function decide(
  group: string,
  plan: Plan,
): Promise<{ live: Record<string, unknown>; set: Record<string, unknown>; diff: DiffRow[]; scrub: string[] } | { step: PackStep }> {
  const key = inputKey(plan.which)
  const id = plan.which === 'http' ? PACK_HTTP_INPUT_ID : PACK_SAMPLE_INPUT_ID
  const got = await readLive(group, plan.which)
  if (got.status === 404) return { step: { key, action: 'error', detail: `${id} is not in ${PACK_ID} here — is the pack installed?` } }
  const live = got.status === 200 ? firstItem(got) : null
  if (!live) {
    return {
      step: {
        key, action: 'error',
        detail: got.status === 200
          ? `not applied — this app could not read the live ${id}, and this endpoint replaces the whole object`
          : scrubbedErrText(got, plan.secrets),
      },
    }
  }
  const decided = plan.edit(live)
  if ('refuse' in decided) return { step: { key, action: 'error', detail: decided.refuse } }
  return { live, set: decided.set, diff: diffOf(live, decided.set), scrub: [...tokensOf(live), ...plan.secrets] }
}

/**
 * GET → overlay → PATCH the whole body of one of the pack's sources. The
 * endpoint is a full replacement (openapi.json, and measured on the group's own
 * sources), so the body is the live object with only the plan's keys changed
 * and the server-owned keys left out. Nothing is sent when nothing would
 * change, and nothing when `approved` (the diff a confirmation showed) is not
 * the diff this read gives: the source moved after it was shown.
 */
async function patchPackInput(group: string, plan: Plan, approved?: readonly DiffRow[]): Promise<PackStep> {
  const key = inputKey(plan.which)
  const d = await decide(group, plan)
  if ('step' in d) return d.step
  if (approved !== undefined && !sameDiff(approved, d.diff)) {
    if (d.diff.length === 0) return { key, action: 'exists', detail: 'nothing left to change — it was applied after this change was shown' }
    return {
      key, action: 'error',
      detail: `not applied — the source changed after this change was shown, so what was confirmed is not what would now be sent. ` +
        `Would now change: ${d.diff.map((r) => r.key).join(', ') || 'nothing'}. Look again, and confirm again.`,
    }
  }
  if (d.diff.length === 0) return { key, action: 'exists', detail: 'already set' }
  const body: Record<string, unknown> = { ...d.live }
  for (const k of SOURCE_SERVER_OWNED) delete body[k]
  Object.assign(body, d.set)
  const r = plan.which === 'http'
    ? await capi('PATCH', packPath(group, `/system/inputs/${PACK_HTTP_INPUT_ID}`), body)
    : await capi('PATCH', packPath(group, `/system/inputs/${PACK_SAMPLE_INPUT_ID}`), body)
  if (r.status < 200 || r.status >= 300) return { key, action: 'error', detail: scrubbedErrText(r, d.scrub), sent: true }
  return { key, action: 'updated', detail: d.diff.map((row) => row.key).join(', ') }
}

/**
 * What `applyPackInput(group, change)` would change, read and decided exactly
 * as it will be — GETs only, nothing written. Pass the diff to
 * `<ConfirmDialog diff>`, and the same diff back as `approved` once confirmed.
 */
export async function previewPackInput(group: string, change: PackInputChange): Promise<PackInputPreview> {
  const plan = await planFor(group, change)
  if (!('which' in plan)) return { ok: false, step: plan }
  const d = await decide(group, plan)
  if ('step' in d) return { ok: false, step: d.step }
  return { ok: true, key: inputKey(plan.which), diff: d.diff }
}

/**
 * Make one change to one of the pack's sources. With `approved` (the diff a
 * confirmation showed, from `previewPackInput`), nothing is sent unless the
 * live source still gives exactly that diff.
 */
export async function applyPackInput(group: string, change: PackInputChange, approved?: readonly DiffRow[]): Promise<PackStep> {
  const plan = await planFor(group, change)
  if (!('which' in plan)) return plan
  return patchPackInput(group, plan, approved)
}

/**
 * Everything an install has to set on the pack's Raw HTTP source, in ONE
 * whole-body PATCH: a free port for the group's hosting, the new token, TLS for
 * the hosting where the source has none of its own (`tlsToSet`), and enabled.
 * This is the call the Guided Setup slice makes after an install.
 */
export function configureHttpInput(
  group: string,
  opts: { port: number; token: string; hosting: Hosting },
  approved?: readonly DiffRow[],
): Promise<PackStep> {
  return applyPackInput(group, { kind: 'configure', ...opts }, approved)
}

/** Move the pack's Raw HTTP source to another port, checked free and inside
 *  what the group's hosting allows. */
export function setSourcePort(group: string, port: number, hosting: Hosting, approved?: readonly DiffRow[]): Promise<PackStep> {
  return applyPackInput(group, { kind: 'port', port, hosting }, approved)
}

/** Replace the pack's Raw HTTP source's auth token (a rotation). The old one
 *  stops working at the next deploy. */
export function setHttpToken(group: string, token: string, approved?: readonly DiffRow[]): Promise<PackStep> {
  return applyPackInput(group, { kind: 'token', token }, approved)
}

/** Start the pack's Raw HTTP source: `disabled` only, plus TLS where the
 *  source has none of its own (`tlsToSet`). Refused while it has no token or
 *  its port is not usable. */
export function enableHttpInput(group: string, hosting: Hosting, approved?: readonly DiffRow[]): Promise<PackStep> {
  return applyPackInput(group, { kind: 'enable', hosting }, approved)
}

/**
 * Start or stop the sample DataGen. Starting it is refused until its own
 * dataset, `gigamon_ami_sample`, exists: the pack cannot create a dataset, and
 * a destination with nowhere to write blocks.
 */
export function setSampleEnabled(group: string, enabled: boolean, approved?: readonly DiffRow[]): Promise<PackStep> {
  return applyPackInput(group, { kind: 'sample', enabled }, approved)
}

// ── Committing the pack's files ─────────────────────────────────────────────

/**
 * What selects this pack's files among a group's pending Git paths: any path
 * with a segment named exactly after the pack. MEASURED: an install lands
 * under `groups/<g>/default/<pack>/` and `groups/<g>/data/packs/<pack>/`; both
 * hold this segment, and so would any other directory Cribl names after the
 * pack (where a PATCH of a pack source lands is not measured). A sibling pack
 * whose id merely starts with this one's does not match: the segment is
 * slash-delimited on both sides.
 */
export const PACK_COMMIT_MARKERS: readonly string[] = Object.freeze([`/${PACK_ID}/`])

/** The two measured directories, as the commit names them when Git reports
 *  nothing pending at all (provision.ts's fallback). */
export const packCommitPaths = (group: string): string[] => [
  `groups/${group}/default/${PACK_ID}`,
  `groups/${group}/data/packs/${PACK_ID}`,
]

/**
 * The key a pack commit's hash is kept under in Guided Setup's commit memory
 * (setupMemory.ts: group → key → {hash, message}). Not a `ResourceKey`: the
 * pack is not one of the stack's rows. provision.ts's stranded-commit repair
 * reads every key of the group, so a hash here is one it will deploy.
 */
export const PACK_COMMIT_KEY = 'onboarding_pack'

/** What a commit of the pack's files in `group` carries, and what else is
 *  pending — the two things its confirmation has to say (provision.ts
 *  `commitScopeFor`). Pure: `pending` is `pendingConfigPaths()`. */
export function packCommitScope(group: string, pending: readonly string[] | null): CommitScope {
  return commitScopeFor(group, packCommitPaths(group), PACK_COMMIT_MARKERS, pending)
}

export interface PackCommitOptions {
  /**
   * Whether this run's pack write changed something (an install, upgrade or
   * remove that succeeded, or a source change that answered `updated`). After
   * one, finding nothing of the pack's to commit is an ERROR — the change would
   * never be committed or deployed — rather than "up to date".
   */
  wrote: boolean
  /**
   * Record a pack commit's hash in Guided Setup's commit memory under
   * `(group, PACK_COMMIT_KEY)`: ProvisionPanel's `recordCommit`, bound. Called
   * as soon as the commit step carries a hash — before the deploy, and also
   * when the deploy then fails — and awaited before this returns. Without it,
   * the stranded-commit repair refuses the pack's commit as "not made by this
   * app" on every later run.
   */
  record: (hash: string, message: string) => Promise<unknown>
}

/** Commit exactly the pack's pending files in `group`, then deploy — Guided
 *  Setup's own machinery (provision.ts `commitMatchingAndDeploy`), not a copy. */
export async function commitAndDeployPack(
  group: string,
  message: string,
  opts: PackCommitOptions,
  onStep?: (r: StepResult) => void,
  onPhase?: OnPhase,
): Promise<StepResult[]> {
  let recorded: Promise<unknown> | null = null
  const step = (r: StepResult) => {
    const hash = r.key === 'commit' ? r.hash : undefined
    if (hash && !recorded) recorded = Promise.resolve().then(() => opts.record(hash, r.message ?? message)).catch(() => false)
    onStep?.(r)
  }
  const nothingCommitted = opts.wrote
    ? `the pack was changed, but Git reports none of its files uncommitted in ${group}, so none of its files were committed ` +
      `and nothing was deployed. Commit and deploy ${group} in Cribl.`
    : null
  const steps = await commitMatchingAndDeploy(message, group, PACK_COMMIT_MARKERS, packCommitPaths(group), step, onPhase, nothingCommitted)
  await recorded
  return steps
}
