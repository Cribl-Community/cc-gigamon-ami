// The onboarding pack's client: read what a worker group has of the pack,
// install it, upgrade it, remove it, and set the three things on its Raw HTTP
// source that only an install can know (port, auth token, TLS for the group's
// hosting), then commit and deploy the pack's files.
//
// ── WHY A MODULE OF ITS OWN, AND NOT pack.ts ────────────────────────────────
// pack.ts is PURE DATA on purpose: the query extractor loads it under plain
// Node, pack.test.ts parses the pack's YAML against it, and its header promises
// it "makes no network call and names no API path". Every export here does both.
// Putting them there would drag `capi`, the KV store and provision.ts into
// everything that only wants an id.
//
// ── WHO REACHES THIS, AND WHAT THAT COST ────────────────────────────────────
// Guided Setup's onboarding panel (components/OnboardingPanel.tsx) and its run
// (cribl/onboarding/run.ts) import this module, so every call here is reachable
// from `src/main.tsx` and is GRANTED in `config/policies.yml` — each pack path
// named with exactly the methods called on it, and no `*` (policyCoverage
// .test.ts holds both directions). Its writes are registered in
// src/cribl/authz.ts under `onboarding_pack.install`, `.configure` and
// `.remove` (and the upgrade's under `.upgrade`), each rendered by a
// `<GatedControl>` on that panel. *(Until 2026-09-24 this
// module was on paths.ts `UNREACHED_MODULES`, built a slice ahead of its UI,
// with its grants deliberately withheld.)*
//
// The in-place upgrade is NOT here: it is packUpgrade.ts, split out so that its
// PATCH was not granted before a control could send it. Upgrade is offered now
// (onboarding/run.ts `runPackUpgrade`, which reads the Raw HTTP source back),
// so that module is reached and its PATCH granted. The pack sources' own
// settings outside an onboarding run — rotate the token (`setHttpToken`), move
// the port (`setSourcePort`), start or stop the sample (`setSampleEnabled`) —
// are offered too, each gated by `onboarding_pack.configure`. *(Corrected
// 2026-09-24, `feat/pack-onboarding-slice3`: this said neither had a control,
// and that their WriteId was withdrawn. On `feat/pack-onboarding-4a`,
// `upgradePack` lived here, so its PATCH was granted for a control that
// rendered refused and could never send it.)*
//
// ── WHAT EVERY WRITE HERE ASSUMES OF ITS CALLER ─────────────────────────────
// Each export that writes is an entry point reached from a confirmed click and
// from nowhere else (CLAUDE.md: nothing writes on load, render or a timer). The
// confirmation that names the pack, its version and the group lives with the
// UI; nothing in here can tell a deliberate click from an accidental one.
//
// WHAT THE UI SLICE HAS TO WIRE, because nothing here can do it for it:
//   * A source change is previewed before it is confirmed: `previewPackInput`
//     returns the before→after (`DiffRow[]`, token values masked) for
//     `<ConfirmDialog diff>`, with GETs only. Pass the diff the person approved
//     to `applyPackInput` (or a named wrapper's `approved`), which refuses and
//     sends nothing when the live source no longer gives that same diff.
//   * `commitAndDeployPack` requires `record`: ProvisionPanel's `recordCommit`,
//     bound to the group and `PACK_COMMIT_KEY`. The stranded-commit repair
//     deploys only a hash in that memory, so an unrecorded pack commit whose
//     deploy failed could never be deployed by this app again. It also requires
//     `wrote`, whether this run's pack write changed anything, because after a
//     change "nothing to commit" is an error, not "up to date".
//   * `readPackState().current` already requires a released version installed
//     from its release; do not re-derive "up to date" from `version`.
//
// ── OWNERSHIP: TWO SIGNALS, AS ACCELERATION'S TEARDOWN HAS ───────────────────
// A copy is this app's only when (1) its version is on `PUBLISHED_PACK_VERSIONS`
// AND (2) the group's pack list names that version's release asset
// (`packReleaseUrl`) as its `source`. The id alone proves nothing — the pack
// list is looked up by it — and a version string is only a string: a same-id
// fork, or a dev build that says 0.1.0, carries both. Remove and Upgrade refuse
// anything that fails either, and say which.
//
// ── SECRETS ─────────────────────────────────────────────────────────────────
// The Raw HTTP source's token is generated by the caller (provision.ts
// `generateToken`, 256 bits) and written into the pack's source ONLY. Nothing
// here returns it, logs it, puts it in a step, a diff or an error, or stores it:
// a failed PATCH's error is scrubbed of the new token and of every token the
// live source already held (`scrubbedErrText`), a diff shows "a new token (not
// shown)", and `readPackState` reports whether a token is set, never what it is.
//
// ── NOT VERIFIED ON A LEADER (the proof install has to) ─────────────────────
//   * That a pack's sources answer at `/m/<g>/p/<pack>/system/inputs/<id>`, and
//     its routes, pipelines, outputs and breakers at the matching `/p/<pack>/…`
//     paths. openapi.json lists every one; no Leader in this project has a pack
//     with these objects installed.
//   * WHERE A PATCH OF A PACK SOURCE LANDS IN GIT. The pack's own files were
//     measured under `groups/<g>/default/<pack>/` and
//     `groups/<g>/data/packs/<pack>/`; an override of a pack source was not. The
//     commit therefore selects every pending path in the group with a
//     `/<pack>/` segment (`PACK_COMMIT_MARKERS`), which holds both measured
//     locations and any other directory named after the pack. Nor is it
//     measured how Git status names a NEW, untracked pack directory: without a
//     trailing slash (`…/default/<pack>`) the marker misses it. Either way the
//     pack flow does not report success: after a write, nothing to commit is an
//     error (`commitAndDeployPack`).
//   * That the pack list's `source` for a copy installed from `PACK_URL` is
//     `PACK_URL` itself, and that an in-place upgrade moves it to the new URL.
//     openapi.json's PackInfo requires `source` ("a file path, URL, or Git URL
//     from which the Pack was installed") and its URL-install and upgrade
//     examples show exactly that, but no install on a Leader here was read back
//     for it. If it is anything else, this fails CLOSED: `verifyInstalled`
//     reports the install as unverified, and Remove and Upgrade keep the copy.
//   * That `PATCH /packs/<id>` accepts `allowCustomFunctions: false`. Only
//     `{source}` was sent on a Leader. openapi.json's PackUpgradeRequest lists
//     the field and says an OMITTED one ALLOWS custom JavaScript functions, so
//     it is sent; a Leader that answers 400 fails the upgrade loudly, with
//     nothing changed.
//   * That the release asset's bytes are the ones `PACK_SHA256` records. The
//     Leader downloads `PACK_URL` itself and `POST /packs` takes no digest, so
//     this app cannot check the hash; it refuses to install until one is
//     recorded (a release exists and was built by pack-release.yml), and checks
//     the version, the source and an object afterwards. See `installRefusal`.

